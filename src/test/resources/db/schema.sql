-- 4. confusable_group : 헷갈리는 묶음 (2026-10-14 추가)
--    같은 묶음의 단어끼리는 한 문제의 보기로 함께 내지 않는다.
--    묶음은 레벨과 무관하게 단어 단위. 보기는 원래 같은 세부 레벨에서만 뽑으므로
