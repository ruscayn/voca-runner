--    한 단어가 여러 묶음에 들어갈 수 있다 (sir 는 {sir, teacher}, {sir, Mr.})
-- ---------------------------------------------------------------------
CREATE TABLE confusable_group (
    confusable_group_id bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reason              varchar(100)  NOT NULL,
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now()
