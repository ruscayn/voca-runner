-- 8. word_exposure : 단어 노출 - 지금 판정 (2026-10-27 추가, 앱이 단어 출제 목록을 만들 때 읽는다)
--    처리별 대상
--      EXCLUDE_WORD    단어 제외 : 단어 (뜻 순번·레벨 비움). 모든 레벨에서 정답으로도, 오답 보기로도 내지 않음
--      EXCLUDE_MEANING 뜻 제외   : 단어 안 뜻 순번. 그 뜻을 모든 레벨 보기에서 뺌. 보일 뜻이 남지 않는 레벨 단어는 제외
--      EXCLUDE_LEVEL   레벨 제외 : 레벨 단어 하나. 그 레벨 단어만 정답으로도, 오답 보기로도 내지 않음
--      KEEP            유지     : 검토했지만 그대로 둠 (단어·뜻·레벨 단어 중 하나, 또는 단어 전체)
--    뜻은 meaning_id(재적재마다 다시 매김)가 아니라 단어 안 뜻 순번(seq)으로 가리킨다.
--    단어의 뜻 순서를 바꾸면 이 표도 함께 고친다
-- ---------------------------------------------------------------------
CREATE TABLE word_exposure (
    word_exposure_id bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word_id          bigint        NOT NULL REFERENCES word (word_id),
    meaning_seq      smallint,
    level_code       varchar(2),
    action           varchar(20)   NOT NULL,
    issue_type       varchar(30)   NOT NULL REFERENCES word_exposure_type (issue_type_code),
    severity         varchar(10),
    reason           varchar(500)  NOT NULL,
    decided_at       date          NOT NULL,
    decided_by       varchar(30)   NOT NULL,
    created_at       timestamptz   NOT NULL DEFAULT now(),
    updated_at       timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT uk_word_exposure_target UNIQUE NULLS NOT DISTINCT (word_id, meaning_seq, level_code),
    CONSTRAINT fk_word_exposure_meaning FOREIGN KEY (word_id, meaning_seq) REFERENCES word_meaning (word_id, seq),
    CONSTRAINT fk_word_exposure_level   FOREIGN KEY (level_code, word_id)  REFERENCES level_word (level_code, word_id),
    CONSTRAINT ck_word_exposure_action  CHECK (action IN ('EXCLUDE_WORD','EXCLUDE_MEANING','EXCLUDE_LEVEL','KEEP')),
    CONSTRAINT ck_word_exposure_target  CHECK (
        (action = 'EXCLUDE_WORD'    AND meaning_seq IS NULL     AND level_code IS NULL) OR
        (action = 'EXCLUDE_MEANING' AND meaning_seq IS NOT NULL AND level_code IS NULL) OR
        (action = 'EXCLUDE_LEVEL'   AND meaning_seq IS NULL     AND level_code IS NOT NULL) OR
        (action = 'KEEP'            AND (meaning_seq IS NULL OR level_code IS NULL))),
    CONSTRAINT ck_word_exposure_severity CHECK (severity IS NULL OR severity IN ('HIGH','MEDIUM','LOW'))
);

COMMENT ON TABLE  word_exposure             IS '단어 노출 (지금 판정). 한 대상(단어 / 뜻 / 레벨 단어)에 한 줄. 같은 단어에 단어 제외가 있으면 다른 줄을 두지 않는다';
COMMENT ON COLUMN word_exposure.word_id     IS '단어 (word_id 는 원본 번호 그대로라 재적재해도 바뀌지 않음)';
COMMENT ON COLUMN word_exposure.meaning_seq IS '뜻 제외·유지의 대상 뜻 (word_meaning.seq). 그 밖에는 NULL';
COMMENT ON COLUMN word_exposure.level_code  IS '레벨 제외·유지의 대상 레벨 단어 (level_word). 그 밖에는 NULL';
COMMENT ON COLUMN word_exposure.action      IS '처리: EXCLUDE_WORD 단어 제외, EXCLUDE_MEANING 뜻 제외, EXCLUDE_LEVEL 레벨 제외, KEEP 유지';
COMMENT ON COLUMN word_exposure.issue_type  IS '이슈 유형 (word_exposure_type)';
COMMENT ON COLUMN word_exposure.severity    IS '강도 HIGH·MEDIUM·LOW (민감 단어만, 그 밖에는 NULL)';
COMMENT ON COLUMN word_exposure.reason      IS '판정 사유';
COMMENT ON COLUMN word_exposure.decided_at  IS '판정 날짜';
COMMENT ON COLUMN word_exposure.decided_by  IS '판정한 사람';

CREATE TRIGGER trg_word_exposure_updated BEFORE UPDATE ON word_exposure FOR EACH ROW EXECUTE FUNCTION set_updated_at();

