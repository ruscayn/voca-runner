-- DB 테스트용 표 (임시 PostgreSQL 에 만든다. 단어 데이터는 넣지 않는다).
-- 원본: docs/output/schema.sql 의 1~6번 (기존 객체 삭제·적재 후 실행 구문 제외)을 그대로 복사했다.
-- 원본을 바꾸면 여기도 같이 바꾼다 (entity 와 다르면 ddl-auto: validate 로 DB 테스트가 시작부터 실패해 알 수 있다).

-- ---------------------------------------------------------------------
-- 1. word : 영어 단어 목록 (표제어)
-- ---------------------------------------------------------------------
CREATE TABLE word (
    word_id       bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    headword      varchar(50)   NOT NULL,
    loanword      varchar(50),
    headword_sub  varchar(100),
    created_at    timestamptz   NOT NULL DEFAULT now(),
    updated_at    timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT uk_word_headword UNIQUE (headword)          -- 대소문자 구분 (May / may)
);

COMMENT ON TABLE  word              IS '영어 단어 목록';
COMMENT ON COLUMN word.headword     IS '표제어. 대소문자 구분';
COMMENT ON COLUMN word.loanword     IS '외래어 표기 (예: elevator → 엘리베이터). 시험 보기에는 쓰지 않는 참고 정보. 없으면 NULL';
COMMENT ON COLUMN word.headword_sub IS '시험 화면에 표제어와 줄바꿈으로 함께 표시할 형태 (예: for the sake of → for one''s sake). 없으면 NULL';

-- ---------------------------------------------------------------------
-- 2. word_meaning : 단어의 한국어 뜻 (단어당 최대 5개)
-- ---------------------------------------------------------------------
CREATE TABLE word_meaning (
    meaning_id  bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word_id     bigint       NOT NULL REFERENCES word (word_id),
    seq         smallint     NOT NULL,
    pos         varchar(20)  NOT NULL,
    meaning_ko  varchar(50)  NOT NULL,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uk_word_meaning_seq UNIQUE (word_id, seq),
    CONSTRAINT ck_word_meaning_seq CHECK (seq BETWEEN 1 AND 5)
);

CREATE INDEX ix_word_meaning_word ON word_meaning (word_id);

COMMENT ON TABLE  word_meaning            IS '단어의 한국어 뜻';
COMMENT ON COLUMN word_meaning.seq        IS '뜻 순서 (1이 가장 흔한 뜻, 최대 5)';
COMMENT ON COLUMN word_meaning.pos        IS '이 뜻의 품사 (noun, verb, adjective ...)';
COMMENT ON COLUMN word_meaning.meaning_ko IS '한국어 뜻. 뒤 괄호는 덧붙임 정보 (예: 2층(영), 핸드백(미))';

-- ---------------------------------------------------------------------
-- 3. level_word : 레벨별 출제 단어와 보여줄 뜻 (시험 출제 단위)
-- ---------------------------------------------------------------------
CREATE TABLE level_word (
    level_word_id bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    level_code    varchar(2)  NOT NULL,
    word_id       bigint      NOT NULL REFERENCES word (word_id),
    meaning1_id   bigint      NOT NULL REFERENCES word_meaning (meaning_id),
    meaning2_id   bigint               REFERENCES word_meaning (meaning_id),
    test_excluded boolean     NOT NULL DEFAULT false,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_level_word UNIQUE (level_code, word_id),
    CONSTRAINT ck_level_word_level CHECK (level_code IN ('A1','A2','B1','B2','C1','C2')),
    CONSTRAINT ck_level_word_meaning_diff CHECK (meaning2_id IS NULL OR meaning1_id <> meaning2_id)
);

CREATE INDEX ix_level_word_level ON level_word (level_code);
CREATE INDEX ix_level_word_level_testable ON level_word (level_code) WHERE test_excluded = false;

COMMENT ON TABLE  level_word               IS '레벨별 출제 단어. 한 레벨에 같은 단어는 1번';
COMMENT ON COLUMN level_word.level_code    IS '세부 레벨 A1~C2 (묶음 A/B/C는 코드에서 처리)';
COMMENT ON COLUMN level_word.meaning1_id   IS '시험 보기에 보여줄 첫 번째 뜻';
COMMENT ON COLUMN level_word.meaning2_id   IS '시험 보기에 보여줄 두 번째 뜻 (없으면 NULL)';
COMMENT ON COLUMN level_word.test_excluded IS 'true면 이 레벨에서 정답 문제로 출제하지 않음 (예: bus 버스, inch A2 인치). 오답 보기로는 사용 가능';

-- ---------------------------------------------------------------------
-- updated_at 자동 갱신 트리거
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
    LANGUAGE plpgsql
    AS 'BEGIN NEW.updated_at := now(); RETURN NEW; END';

CREATE TRIGGER trg_word_updated          BEFORE UPDATE ON word          FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_word_meaning_updated  BEFORE UPDATE ON word_meaning  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_level_word_updated    BEFORE UPDATE ON level_word    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- 4. confusable_group : 헷갈리는 단어 묶음 (2026-10-14 추가)
--    같은 묶음의 단어끼리는 한 문제의 보기로 함께 내지 않는다.
--    묶음은 레벨과 무관하게 단어 단위. 보기는 원래 같은 세부 레벨에서만 뽑으므로
--    두 단어가 같은 레벨에 있을 때만 규칙이 걸린다.
--    한 단어가 여러 묶음에 들어갈 수 있다 (sir 는 {sir, teacher}, {sir, Mr.})
-- ---------------------------------------------------------------------
CREATE TABLE confusable_group (
    confusable_group_id bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reason              varchar(100)  NOT NULL,
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now()
);

COMMENT ON TABLE  confusable_group        IS '헷갈리는 단어 묶음. 같은 묶음 단어끼리는 한 문제의 보기로 함께 내지 않음';
COMMENT ON COLUMN confusable_group.reason IS '헷갈리는 이유 (예: 선생님, 완전히)';

-- ---------------------------------------------------------------------
-- 5. confusable_group_word : 묶음에 속한 단어
--    단어·묶음이 삭제되면 함께 삭제 (ON DELETE CASCADE)
-- ---------------------------------------------------------------------
CREATE TABLE confusable_group_word (
    confusable_group_id bigint       NOT NULL REFERENCES confusable_group (confusable_group_id) ON DELETE CASCADE,
    word_id             bigint       NOT NULL REFERENCES word (word_id) ON DELETE CASCADE,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_confusable_group_word PRIMARY KEY (confusable_group_id, word_id)
);

CREATE INDEX ix_confusable_group_word_word ON confusable_group_word (word_id);

COMMENT ON TABLE confusable_group_word IS '헷갈리는 단어 묶음에 속한 단어. 묶음당 2개 이상이어야 의미 있음';

CREATE TRIGGER trg_confusable_group_updated BEFORE UPDATE ON confusable_group FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- 6. test_session : 시험 1회 (2026-10-23 추가, 시험 1회 1행)
--    재시작·배포 때 진행 중 시험이 사라지지 않도록 메모리 대신 DB 에 저장
-- ---------------------------------------------------------------------
CREATE TABLE test_session (
    test_session_id     uuid          PRIMARY KEY,
    level_code          varchar(2)    NOT NULL,
    direction           varchar(10)   NOT NULL,
    question_count      integer       NOT NULL,
    time_limit_sec      integer       NOT NULL,
    device_id           varchar(36)   NOT NULL,
    client_ip           varchar(45)   NOT NULL,
    status              varchar(12)   NOT NULL,
    questions_delivered boolean       NOT NULL DEFAULT false,
    started_at          timestamptz   NOT NULL,
    deadline            timestamptz   NOT NULL,
    submitted_at        timestamptz,
    correct_count       integer,
    score               integer,
    option_ids          integer[]     NOT NULL,
    correct_option_no   bytea         NOT NULL,
    selected_option_no  bytea         NOT NULL,
    version             integer       NOT NULL DEFAULT 0,
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT ck_test_session_level  CHECK (level_code IN ('A1','A2','B1','B2','C1','C2')),
    CONSTRAINT ck_test_session_status CHECK (status IN ('IN_PROGRESS','COMPLETED','EXPIRED'))
);
CREATE INDEX ix_test_session_status_deadline ON test_session (status, deadline);
CREATE INDEX ix_test_session_device ON test_session (device_id) WHERE status = 'IN_PROGRESS';
CREATE INDEX ix_test_session_ip     ON test_session (client_ip) WHERE status = 'IN_PROGRESS';

COMMENT ON TABLE  test_session                     IS '시험 1회 (정답지·고른 답·채점 결과). 진행 중·결과 보관 중인 시험만 두고, 보관 시간이 지나면 정리 작업이 삭제';
COMMENT ON COLUMN test_session.test_session_id     IS '시험 id (시험 화면 주소에 쓰는 UUID)';
COMMENT ON COLUMN test_session.level_code          IS '세부 레벨 A1~C2';
COMMENT ON COLUMN test_session.direction           IS '출제 방향 (EN_KO: 영어 단어 → 한국어 뜻 고르기)';
COMMENT ON COLUMN test_session.question_count      IS '문항 수';
COMMENT ON COLUMN test_session.time_limit_sec      IS '문제당 제한 시간 (초)';
COMMENT ON COLUMN test_session.device_id           IS '시작한 기기 구분 값 (쿠키 VR_DEVICE). 기기당 진행 중 시험 1개';
COMMENT ON COLUMN test_session.client_ip           IS '시작한 IP. IP당 진행 중 시험 상한(50개) 확인용';
COMMENT ON COLUMN test_session.status              IS '상태: IN_PROGRESS 진행 중, COMPLETED 제출 완료, EXPIRED 무효(중도 이탈·마감 초과)';
COMMENT ON COLUMN test_session.questions_delivered IS '시험 화면이 문제를 받아 갔는지. 시작 후 5분 안에 받아 가지 않으면 정리 (연결 끊김 대비)';
COMMENT ON COLUMN test_session.started_at          IS '시작 시각';
COMMENT ON COLUMN test_session.deadline            IS '마감 시각. 지나면 제출 불가 (시작 + 문항 수 × 제한 시간 + 여유, 분 단위 올림)';
COMMENT ON COLUMN test_session.submitted_at        IS '제출 시각. 결과는 이 시각부터 2시간 보관. 제출 전이면 NULL';
COMMENT ON COLUMN test_session.correct_count       IS '맞힌 문항 수. 제출 전이면 NULL';
COMMENT ON COLUMN test_session.score               IS '점수 0~100. 제출 전이면 NULL';
COMMENT ON COLUMN test_session.option_ids          IS '보기 level_word_id 목록 (문항 수 × 4). 문항 n의 보기 i = [(n-1)*4 + i]';
COMMENT ON COLUMN test_session.correct_option_no   IS '문항별 정답 보기 번호 1~4 (1바이트씩)';
COMMENT ON COLUMN test_session.selected_option_no  IS '문항별 고른 보기 번호 1~4, 0 = 시간 초과·미응답 (1바이트씩)';
COMMENT ON COLUMN test_session.version             IS '동시 수정 방지용 버전 (같은 시험을 동시에 두 번 제출하면 하나만 반영)';
COMMENT ON COLUMN test_session.created_at          IS '행 생성 시각';
COMMENT ON COLUMN test_session.updated_at          IS '행 수정 시각 (트리거로 갱신)';

CREATE TRIGGER trg_test_session_updated BEFORE UPDATE ON test_session FOR EACH ROW EXECUTE FUNCTION set_updated_at();
